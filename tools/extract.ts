/**
 * Extracts every data constant and engine from the legacy page.
 *
 *   data/legacy/<NAME>.json            one file per constant (TS, LIB, REG, SRC, NUT, FT, SELL, CALLS,
 *                                      EVENTS, POL, DEVT, ABOUT, MAP, APIS)
 *   packages/engines/src/legacy/*.js   the three engines, verbatim, wrapped as ES modules
 *
 * Fails (exit 1) if a constant or engine is missing. Count checks run in tools/check-data.ts.
 * Usage: pnpm extract   (or: tsx tools/extract.ts <path-to-legacy-html>)
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const htmlPath = resolve(root, process.argv[2] ?? 'legacy/platform_v33.html');
const lines = readFileSync(htmlPath, 'utf8').split(/\r?\n/);

export const CONSTANTS = [
  'TS', 'LIB', 'REG', 'SRC', 'NUT', 'FT', 'SELL', 'CALLS', 'EVENTS', 'POL', 'DEVT', 'ABOUT', 'MAP', 'APIS',
] as const;

const outData = join(root, 'data', 'legacy');
mkdirSync(outData, { recursive: true });

const missing: string[] = [];
for (const name of CONSTANTS) {
  const prefix = `const ${name} = `;
  const line = lines.find((l) => l.startsWith(prefix));
  if (!line) {
    missing.push(name);
    continue;
  }
  // A line may declare several constants: "const DEVT = [...], DEVF = {...}, PROG = [...];"
  const names = [name, ...[...line.matchAll(/[\]}]\s*,\s*([A-Z][A-Z0-9_]*)\s*=\s*[[{"]/g)].map((m) => m[1]!)];
  // The legacy page's own literals (JSON plus a few JS arrays); evaluated, never executed against a DOM.
  const values = new Function(`${line}\nreturn { ${names.join(', ')} };`)() as Record<string, unknown>;
  for (const n of names) {
    writeFileSync(join(outData, `${n}.json`), JSON.stringify(values[n]));
    console.log(`${n}: ${(JSON.stringify(values[n]).length / 1024).toFixed(0)} KB`);
  }
}

// Engines: UMD blocks that start with "(function (root, factory)" and assign root.<Name>.
const ENGINES = [
  { name: 'CottidStaples', file: 'staples.js', deps: [] as string[] },
  { name: 'CottidForecast', file: 'forecast.js', deps: [] as string[] },
  { name: 'CottidAdvisor', file: 'advisor.js', deps: ['forecast', 'staples'] },
];
const outEng = join(root, 'packages', 'engines', 'src', 'legacy');
mkdirSync(outEng, { recursive: true });
for (const eng of ENGINES) {
  const at = lines.findIndex((l) => l.includes(`root.${eng.name} = factory(`));
  if (at < 0) {
    missing.push(eng.name);
    continue;
  }
  const start = lines.slice(0, at).findLastIndex((l) => /\(function \(root, factory\)/.test(l));
  // The block ends at the first unindented line that closes the factory: "});"
  let end = at;
  while (end < lines.length && !/^\}\);?\s*$/.test(lines[end]!)) end++;
  if (start < 0 || end >= lines.length) {
    missing.push(eng.name);
    continue;
  }
  const body = lines.slice(start, end + 1).join('\n');
  const imports = eng.deps.map((d) => `import ${d} from './${d}.js';`).join('\n');
  const req = eng.deps.length
    ? `const require = (p) => (p.includes('forecast') ? forecast : staples);`
    : `const require = undefined;`;
  writeFileSync(
    join(outEng, eng.file),
    `// GENERATED by tools/extract.ts from legacy/platform_v33.html (${eng.name}). Do not edit; re-run pnpm extract.\n` +
      `/* eslint-disable */\n// @ts-nocheck\n${imports}\n${req}\nconst module = { exports: {} };\n${body}\nexport default module.exports;\n`,
  );
  console.log(`${eng.name}: lines ${start + 1}-${end + 1} -> ${eng.file}`);
}

if (missing.length) {
  console.error(`Missing from the legacy page: ${missing.join(', ')}`);
  process.exit(1);
}
